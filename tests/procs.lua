local checks=0
local function check(v,m) assert(v,m); checks=checks+1 end
local oldAuras,oldTime=C_UnitAuras,GetTime
local now,auras,sounds=100,{},{}
GetTime=function() return now end
PlaySoundFile=function(path,channel) sounds[#sounds+1]={path,channel} end
C_UnitAuras={GetUnitAuraBySpellID=function(unit,id) return unit=="player" and auras[id] or nil end,
    GetAuraDataByIndex=function() return nil end}
addon.db.procs=addon:Clone(addon.defaults.procs)
addon.db.showIgnite=true
addon:StopProcTest(); addon:ApplyProcSettings()
local frame=addon.procDisplay
check(not frame.cards.clearcasting:IsShown(),"no false proc without aura")
auras[12536]={applications=0,expirationTime=115}; fire("UNIT_AURA","player")
check(frame.cards.clearcasting:IsShown(),"buff reveals Clearcasting without an active spellbook entry")
check(#sounds==1 and sounds[1][1]:find("ProcChime.wav",1,true) and sounds[1][2]=="Master","gain plays selected sound once")
fire("UNIT_AURA","player"); frame.scripts.OnUpdate(frame,.2)
check(#sounds==1,"repeated events and polls cannot repeat gain sound")
now=101; addon:UpdateProcDisplay(false)
check(frame.cards.clearcasting.timer.text=="14.0s","readable timer counts down")
auras[12536]=nil; fire("UNIT_AURA","player")
check(not frame.cards.clearcasting:IsShown(),"consumption hides proc")
now=103; auras[12536]={applications=0,expirationTime=118}; fire("UNIT_AURA","player")
check(#sounds==2,"a new gain alerts again")
auras[400625]={applications=1,expirationTime=123}; fire("UNIT_AURA","player")
check(#sounds==2 and frame.cards.heating.count.text=="1/3","Heating Up shows partial stacks silently")
check(not frame.cards.heating.readyGlow:IsShown(),"partial stacks have no maximum halo")
now=105; auras[400625].applications=3; fire("UNIT_AURA","player")
check(#sounds==3 and frame.cards.heating.count.text=="3/3","Heating Up sounds at three stacks")
check(frame.cards.heating.readyGlow:IsShown() and frame.cards.heating.callout.text:find("MAX STACKS",1,true),"maximum stacks show the distinct gold halo and explicit callout")
now=106; auras[400625].expirationTime=126; fire("UNIT_AURA","player")
check(#sounds==3,"full-stack refresh cannot spam sounds")
now=108; auras[400625].applications=secretNumber(); auras[400625].expirationTime=secretNumber(); fire("UNIT_AURA","player")
check(frame.cards.heating.count.values[1]==auras[400625].applications and #sounds==3,"secret stacks pass only to native formatter")
check(frame.cards.heating.timer.text=="Timer unavailable","secret expiry never enters subtraction")
check(not frame.cards.heating.readyGlow:IsShown(),"unreadable stacks cannot display a maximum halo")
now=109; auras[400625].applications=3; fire("UNIT_AURA","player")
check(#sounds==3,"temporarily protected stacks cannot re-arm threshold sound")
auras[12536]=secretNumber(); fire("UNIT_AURA","player")
check(not frame.cards.clearcasting:IsShown(),"secret aura object hides safely")
now=110; auras[12536]={applications=0,expirationTime=125}; fire("UNIT_AURA","player")
check(#sounds==3,"unavailable read does not re-arm gain sound")
addon.db.procs.effects.clearcasting.enabled=false; addon:ApplyProcSettings()
check(not frame.cards.clearcasting:IsShown(),"per-effect switch applies immediately")
addon.db.procs.enabled=false; addon:ApplyProcSettings()
check(not frame.cards.heating:IsShown(),"master switch hides normal alerts")
known={}; addon:HandleCommand("procs test")
check(addon.procTest and frame.testLabel:IsShown(),"test starts without learned talents")
for _,def in ipairs(addon.procTypes) do check(frame.cards[def.key]:IsShown(),"all-effects test includes "..def.label) end
check(not addon.db.procs.enabled and not addon.db.procs.effects.clearcasting.enabled,"test never changes saved switches")
addon:TestProc("fingers","consume")
check(frame.cards.fingers.count.text=="1/2","test charge use decrements Fingers")
check(not frame.cards.fingers.readyGlow:IsShown(),"spending a charge removes the maximum halo")
addon:TestProc("fingers","consume")
check(not frame.cards.fingers:IsShown(),"last test charge removes alert")
addon:TestProc("heating","expire")
check(not frame.cards.heating:IsShown(),"expire selected removes its simulation")
for i=1,4 do addon:TestProc("heating","gain") end
check(frame.cards.heating.count.text=="3/3","gain test builds and caps maximum stacks")
now=131; frame.scripts.OnUpdate(frame,.2)
check(not frame.cards.ignite:IsShown() and not frame.cards.heating:IsShown(),"test auras expire at individual durations")
now=150; frame.scripts.OnUpdate(frame,.2)
check(not addon.procTest and not frame.testLabel:IsShown(),"test session automatically ends")
addon:HandleCommand("procs test"); combat=true; fire("PLAYER_REGEN_DISABLED")
check(not addon.procTest,"entering combat immediately ends simulations")
check(addon:TestProc("all")==false and not addon.procTest,"tests cannot start in combat")
combat=false; addon:HandleCommand("procs")
check(addon.settings.pages.Procs:IsShown(),"proc command opens settings")
check(addon.settings.tabs.Support.point[3]<addon.settings.tabs.Procs.point[3],"Support stays last")
addon.db.procs.enabled=true; addon.db.procs.locked=false; addon:ApplyProcSettings()
check(frame.handle:IsShown(),"unlock shows drag handle")
frame.scripts.OnDragStop()
check(addon.db.procs.point=="TOP" and addon.db.procs.y==-150,"drag stop persists independent position")
check(not addon:ProcDefinition("wake") and not frame.cards.wake,"removed Wake of Fire has no tracking or preview card")
check(frame.cards.ignite.icon.texture=="Interface\\Icons\\Spell_Fire_Incinerate","Ignite uses a reliable explicit fire texture")
addon:HandleCommand("procs stop")
check(not addon.procTest,"stop restores real tracking")
addon.db.procs.sound=false
local played=#sounds; addon:PlayProcSound("missiles",true)
check(#sounds==played+1 and sounds[#sounds][1]:find("ProcPulse.wav",1,true),"explicit preview plays selected sound despite master sound switch")
C_UnitAuras,GetTime=oldAuras,oldTime
io.write("Passed ",checks," proc lifecycle, sound, protection, settings, and simulation checks.\n")
